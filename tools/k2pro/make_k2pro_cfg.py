def apply(text):
    for desc, old, new in CHANGES:
        n = text.count(old)
        if n != 1:
            sys.exit("make_k2pro_cfg: '%s' matched %d times (want 1). The K2 "
                     "config changed: update the script." % (desc, n))
        text = text.replace(old, new)
    for desc, old, new, want in CHANGES_ALL:
        n = text.count(old)
        if n != want:
            sys.exit("make_k2pro_cfg: '%s' matched %d times (want %d)"
                     % (desc, n, want))
        text = text.replace(old, new)
    first, rest = text.split('\n', 1)
    if not first.startswith('# Creality K2 / F021'):
        sys.exit("make_k2pro_cfg: unexpected first line %r" % first)
    return HEADER + rest.rstrip('\n') + '\n' + EXTRA


def main():
    with open(SRC, encoding='utf-8', newline='') as f:
        text = f.read()
    if '\r' in text:
        sys.exit("make_k2pro_cfg: %s has CR line endings" % SRC)
    out = apply(text)
    left = [c for c in ('position_max: 262', 'position_max: 270', 'Y261',
                        'Y265.5', 'X130 Y125', 'resistance1: 260000',
                        'max_power: 0.5', '[hark_bed_power]')
            if c in out]
    if left:
        sys.exit("make_k2pro_cfg: K2 values left in the output: %s" % left)
    with open(DST, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    print("wrote %s (%d changes)" % (os.path.relpath(DST, ROOT),
                                     len(CHANGES) + len(CHANGES_ALL)))


if __name__ == '__main__':
    main()
